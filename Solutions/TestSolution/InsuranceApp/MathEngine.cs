namespace InsuranceApp;

public class MathEngine
{
     public int Addition( int op1, int op2)
    {
        return op1+op2;
    }

    public int Subtraction(int a, int b)
    {
        return a - b;
    }

    public int Multiplication(int a, int b)
    {
        return a * b;
    }

    public int Division(int a, int b)
    {
        return a / b;
    }
}
